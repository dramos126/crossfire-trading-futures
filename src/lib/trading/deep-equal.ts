/**
 * Structural equality over the shapes a param blob holds — scalars, plain
 * objects, and arrays of them.
 *
 * Exported because `deployment-groups.ts` needs exactly this comparison to
 * decide whether a save touched session config, and **`JSON.stringify` is not
 * a substitute**: it is key-order-sensitive, so two equal objects built by
 * different code paths compare unequal. Here that direction is harmless; there
 * it retires a safety banner the operator never answered.
 */
export function deepEqual(a: unknown, b: unknown): boolean {
  if (a === b) return true;
  if (typeof a !== typeof b) return false;
  if (Array.isArray(a) && Array.isArray(b)) {
    if (a.length !== b.length) return false;
    for (let i = 0; i < a.length; i++) {
      if (!deepEqual(a[i], b[i])) return false;
    }
    return true;
  }
  if (isPlainObject(a) && isPlainObject(b)) {
    const ak = Object.keys(a);
    const bk = Object.keys(b);
    if (ak.length !== bk.length) return false;
    for (const k of ak) {
      if (!(k in b)) return false;
      if (!deepEqual((a as Record<string, unknown>)[k], (b as Record<string, unknown>)[k])) {
        return false;
      }
    }
    return true;
  }
  return false;
}

function isPlainObject(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}
